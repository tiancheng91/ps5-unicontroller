#!/usr/bin/env python3
"""Generate safely escaped payload identity from the actual checkout and CI label."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess


def git_value(*args):
    try:
        return subprocess.check_output(
            ["git", *args], stderr=subprocess.DEVNULL, text=True
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def identity(version, branch, commit):
    if not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}|unknown", commit):
        raise ValueError("invalid checkout commit")
    if (
        not version
        or len(version) > 128
        or any(ord(c) < 32 or ord(c) == 127 for c in version)
    ):
        raise ValueError("invalid version label")
    if (
        not branch
        or len(branch) > 255
        or any(ord(c) < 32 or ord(c) == 127 for c in branch)
    ):
        raise ValueError("invalid branch label")
    label = (
        (version if version.startswith("v") else "v" + version)
        if version != "dev"
        else branch
    )
    return {
        "version": version,
        "build_id": f"{label} + {commit[:12]}",
        "commit": commit,
        "branch": branch if version == "dev" else "",
    }


def c_literal(value):
    return json.dumps(value, ensure_ascii=True).replace("?", r"\?")


def header(info):
    # Two layers of escaping: JSON for HTTP, then a C string containing that JSON.
    # No branch name ever becomes a shell command, make variable or C token.
    fragment = json.dumps(info, ensure_ascii=True, separators=(",", ":"))[1:-1]
    return (
        "/* Generated by tools/build_info.py; do not edit. */\n"
        "#ifndef UC_GENERATED_BUILD_INFO_H\n#define UC_GENERATED_BUILD_INFO_H\n"
        f"#define UC_VERSION {c_literal(info['version'])}\n"
        f"#define UC_BUILD_METADATA_JSON {c_literal(fragment)}\n#endif\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("build/build_info.h"))
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    try:
        info = identity(
            os.environ.get("UC_BUILD_VERSION", "dev"),
            os.environ.get("UC_BUILD_BRANCH")
            or git_value("symbolic-ref", "--short", "HEAD")
            or "detached",
            git_value("rev-parse", "HEAD") or "unknown",
        )
        if args.json:
            print(json.dumps(info, ensure_ascii=True))
            return
        content = header(info)
        if not args.output.exists() or args.output.read_text() != content:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            temporary = args.output.with_suffix(".h.tmp")
            temporary.write_text(content, encoding="ascii")
            temporary.replace(args.output)
    except (ValueError, OSError) as error:
        parser.exit(1, f"build metadata: {error}\n")


if __name__ == "__main__":
    main()
