#!/usr/bin/env python3
"""Embed offline HTML, CSS and JS. URLs are explicit; no filesystem traversal."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
pages = {
    "uc_index_html": "web/control/index.html",
    "uc_controller_html": "web/controller/index.html",
    "uc_settings_html": "web/control/settings.html",
}
assets = sorted(p for p in (root / "web").rglob("*") if p.suffix in (".css", ".js"))
out = root / "build/assets.c"
out.parent.mkdir(parents=True, exist_ok=True)
with out.open("w") as f:
    f.write('/* Generated by tools/embed_assets.py. */\n#include "assets.h"\n')

    def emit(name, path):
        raw = path.read_bytes() + b"\0"
        f.write("const char " + name + "[] = {\n")
        for start in range(0, len(raw), 24):
            f.write(",".join(str(b) for b in raw[start : start + 24]) + ",\n")
        f.write("};\n")

    for name, path in pages.items():
        emit(name, root / path)
    for i, path in enumerate(assets):
        emit("uc_resource_" + str(i), path)
    f.write("const struct uc_asset uc_assets[] = {\n")
    for i, path in enumerate(assets):
        url = "/assets/" + path.relative_to(root / "web").as_posix()
        mime = (
            "text/css; charset=utf-8"
            if path.suffix == ".css"
            else "application/javascript; charset=utf-8"
        )
        f.write('{"%s", "%s", uc_resource_%d},\n' % (url, mime, i))
    f.write(
        "};\nconst size_t uc_assets_count = sizeof(uc_assets)/sizeof(uc_assets[0]);\n"
    )
